import fs from 'node:fs';
const page='posts.html', css='assets/posts-page.css', core='assets/site-shell-core.css';
let p=fs.readFileSync(page,'utf8'), c=fs.readFileSync(core,'utf8');
const styles=[...p.matchAll(/<style>([\s\S]*?)<\/style>/g)];
if(styles.length!==1) throw new Error('posts style count '+styles.length);
const extracted=styles[0][1].trim()+'\n\n/* LEGAL_INFO_ENGLISH_OFF_V1 - 법률정보 목록 상단 영문 라벨 숨김 */\n.section>.container>.label{display:none!important}\n.section>.container>.title{margin-top:0!important}\n';
if(fs.existsSync(css)) throw new Error('posts-page.css exists');
fs.writeFileSync(css,extracted);
p=p.replace(styles[0][0],'<link rel="stylesheet" href="/assets/posts-page.css?v=20260913">');
const block='/* LEGAL_INFO_ENGLISH_OFF_V1 - 법률정보 목록 상단 영문 라벨 숨김 */\nbody:has(#posts) .section>.container>.label{display:none!important}\nbody:has(#posts) .section>.container>.title{margin-top:0!important}\n';
if((c.split(block).length-1)!==1) throw new Error('legal info core block mismatch');
c=c.replace(block,'');
fs.writeFileSync(page,p); fs.writeFileSync(core,c);
console.log('extracted posts inline CSS and moved legal-info-only core rule');
